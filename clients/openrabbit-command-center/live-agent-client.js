"use strict";

(()=>{
  const drawer=document.getElementById("communicationsDrawer");
  const runBtn=document.getElementById("communicationsRun");
  const summarizeBtn=document.getElementById("summarizeBtn");
  const aiSummary=document.getElementById("aiSummary");
  const toast=document.getElementById("communicationsToast");
  if(!drawer||!runBtn)return;

  function showToast(message){if(!toast)return;toast.textContent=message;toast.classList.add("show");setTimeout(()=>toast.classList.remove("show"),2400)}
  function selectedContext(){
    const card=document.querySelector(".conversation.selected");
    return {
      workspace:"communications",
      channel:document.getElementById("threadChannel")?.textContent||null,
      contact:document.getElementById("threadContact")?.textContent||null,
      linkedDeal:document.getElementById("contextDeal")?.textContent||null,
      subject:card?.querySelector("strong")?.textContent||null,
      snippet:card?.querySelector("p")?.textContent||null,
      liveSource:card?.dataset.live||null,
      messageId:card?.dataset.messageId||null,
      currentSummary:aiSummary?.textContent||null,
    };
  }
  async function agentRun(input,context=selectedContext()){
    const res=await fetch("/api/agent/run",{method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify({input,context})});
    const payload=await res.json();
    if(!res.ok)throw new Error(payload.error||"OpenRabbit agent request failed");
    return payload;
  }

  runBtn.addEventListener("click",async(event)=>{
    event.preventDefault();event.stopImmediatePropagation();
    const area=drawer.querySelector("textarea");const input=area?.value.trim();if(!input){area?.focus();return}
    runBtn.disabled=true;runBtn.textContent="OpenRabbit is analyzing…";
    try{
      const result=await agentRun(input);
      let output=drawer.querySelector(".live-agent-output");if(!output){output=document.createElement("div");output.className="live-agent-output";output.style.cssText="margin-top:14px;padding:12px;border:1px solid #29476b;border-radius:10px;color:#cdd9eb;white-space:pre-wrap;line-height:1.5";drawer.appendChild(output)}
      output.textContent=result.text||"OpenRabbit returned no text response.";showToast(`Live OpenRabbit response · ${result.model||"OpenAI"}`);
    }catch(error){showToast(error.message);}
    finally{runBtn.disabled=false;runBtn.textContent="Run Request";}
  },true);

  summarizeBtn?.addEventListener("click",async(event)=>{
    const card=document.querySelector(".conversation.selected");if(card?.dataset.live!=="gmail")return;
    event.preventDefault();event.stopImmediatePropagation();summarizeBtn.disabled=true;summarizeBtn.textContent="Summarizing…";
    try{
      const result=await agentRun("Summarize this live Gmail message for me. Identify what matters, whether a response is needed, any deadlines or risks, and the best next action. Be concise.");
      if(aiSummary)aiSummary.textContent=result.text;showToast("Live Gmail summary generated by OpenRabbit.");
    }catch(error){showToast(error.message)}finally{summarizeBtn.disabled=false;summarizeBtn.textContent="Summarize"}
  },true);
})();